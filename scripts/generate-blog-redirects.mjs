/**
 * Build step: prepend 301s to dist/_redirects for blog URLs that carry another
 * locale's slug (e.g. /de/blog/moins-temps-documenter-ia-plus-soigner/).
 * Older language switchers kept the slug when changing locale, and Google
 * still crawls those links as 404s. Each one now redirects to the real
 * translation in the requested locale.
 *
 *   node scripts/generate-blog-redirects.mjs [distDir]
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const BLOG_DIR = "src/content/blog";
const DEFAULT_LOCALE = "en";

const prefix = (locale) => (locale === DEFAULT_LOCALE ? "" : `/${locale}`);

export async function buildBlogRedirects(blogDir = BLOG_DIR) {
  const groups = new Map();
  const localeSlugs = new Map();
  for (const locale of await readdir(blogDir)) {
    localeSlugs.set(locale, new Set());
    for (const file of await readdir(join(blogDir, locale))) {
      if (!/\.mdx?$/.test(file)) continue;
      const slug = file.replace(/\.mdx?$/, "");
      const key = (await readFile(join(blogDir, locale, file), "utf8")).match(/^translationKey:\s*["']?([a-z0-9-]+)/m)?.[1];
      if (!key) throw new Error(`generate-blog-redirects: ${locale}/${file} has no translationKey`);
      groups.set(key, { ...groups.get(key), [locale]: slug });
      localeSlugs.get(locale).add(slug);
    }
  }

  const lines = [];
  for (const group of groups.values()) {
    const slugs = new Set(Object.values(group));
    for (const [locale, own] of Object.entries(group)) {
      const target = `${prefix(locale)}/blog/${own}/`;
      for (const slug of slugs) {
        // Never shadow a real post that happens to use this slug in this locale.
        if (localeSlugs.get(locale).has(slug)) continue;
        const from = `${prefix(locale)}/blog/${slug}`;
        lines.push(`${from} ${target} 301`, `${from}/ ${target} 301`);
      }
    }
  }
  return lines;
}

const distDir = resolve(process.argv[2] ?? "dist");
const lines = await buildBlogRedirects();
// Prepend: Cloudflare counts every rule after a splat (/en/*) as dynamic, capped at 100.
const file = join(distDir, "_redirects");
const existing = await readFile(file, "utf8");
await writeFile(file, `# Generated by scripts/generate-blog-redirects.mjs: cross-locale blog slugs.\n${lines.join("\n")}\n\n${existing}`);
console.log(`generate-blog-redirects: ${lines.length} rules`);
